import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {createClient} from '@supabase/supabase-js';
const {chromium}=createRequire('D:/devcache/npm/_npx/e41f203b7505f1fb/node_modules/playwright/package.json')('playwright');
process.loadEnvFile('.env.local');
if(new URL(process.env.NEXT_PUBLIC_SUPABASE_URL).hostname!=='127.0.0.1')throw Error('Local only');
const db=createClient(process.env.NEXT_PUBLIC_SUPABASE_URL,process.env.SUPABASE_SERVICE_ROLE_KEY);
const ck=({data,error})=>{if(error)throw Error(error.message);return data;};
const fixtures=JSON.parse(fs.readFileSync('output/evidence/fixtures.json'));
const account=JSON.parse(fs.readFileSync('output/evidence/accounts.json'))['Audit Alice'];
const school=fixtures.institutes[0];
const browser=await chromium.launch({args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
const context=await browser.newContext({storageState:'output/evidence/Audit-Alice-session.json',permissions:['camera','geolocation'],geolocation:{latitude:23.03,longitude:72.58},viewport:{width:1280,height:1100}});
const page=await context.newPage();
async function photo(){
 await page.locator('#visit-photo-capture').click();
 await page.getByRole('button',{name:'Capture',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'hidden',timeout:30000});
 await page.waitForFunction(()=>Boolean(document.querySelector('input[name=photo_path]')?.value),{timeout:30000});
}
await page.goto('http://127.0.0.1:3000/log');
await page.getByRole('combobox').first().click();await page.getByRole('option',{name:'First meeting done',exact:true}).click();
await page.locator('#follow-up-date').fill(fixtures.future);
await page.getByRole('button',{name:'Call',exact:true}).click();
await page.locator('#notes').fill('Synthetic report: open follow-up call requested.');
await page.screenshot({path:'output/evidence/R5-open.png',fullPage:true});
await photo();
await page.getByRole('button',{name:'Save and check out',exact:true}).click();
try{await page.waitForURL('**/?filed=1',{timeout:30000});}catch(e){console.log(await page.locator('body').innerText());throw e;}
const visitsBefore=ck(await db.from('visits').select('id,next_action,reported_at').eq('institute_id',school.id));
assert(visitsBefore.some(v=>v.next_action==='call'&&v.reported_at));
const tasksBefore=ck(await db.from('follow_up_tasks').select('*').eq('institute_id',school.id));
assert(tasksBefore.some(t=>t.kind==='call'&&t.due_date===fixtures.future&&!t.done_at));
const purpose=fixtures.purposes.find(p=>p.activity==='meeting'&&p.label==='Follow-up');
const plan=ck(await db.from('daily_plans').insert({member:account.id,date:fixtures.today,institute_id:school.id,purpose:purpose.label,purpose_id:purpose.id,checkin_at:new Date().toISOString(),checkin_lat:23.03,checkin_lng:72.58,checkout_missing:false}).select('id').single());
await page.goto(`http://127.0.0.1:3000/log?plan=${plan.id}`);
await page.getByRole('combobox').first().click();await page.getByRole('option',{name:'Session done',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Call',exact:true}).count(),0);
await page.getByRole('combobox').first().click();await page.getByRole('option',{name:'Not Interested',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Call',exact:true}).count(),0);
await page.locator('#notes').fill('Synthetic report: not interested, cancel pending follow-ups.');
await page.screenshot({path:'output/evidence/R5-not-interested.png',fullPage:true});
await photo();
await page.getByRole('button',{name:'Save and check out',exact:true}).click();
try{await page.waitForURL('**/?filed=1',{timeout:30000});}catch(e){console.log(await page.locator('body').innerText());throw e;}
const tasksAfter=ck(await db.from('follow_up_tasks').select('*').eq('institute_id',school.id));
assert.equal(tasksAfter.length,tasksBefore.length);
assert(tasksAfter.every(t=>t.done_at&&t.outcome==='cancelled'));
const visitsAfter=ck(await db.from('visits').select('id,next_action').eq('institute_id',school.id));
assert(visitsBefore.every(v=>visitsAfter.some(a=>a.id===v.id)));
assert.equal(ck(await db.from('institutes').select('status').eq('id',school.id).single()).status,'Not Interested');
await page.goto('http://127.0.0.1:3000/pending/follow-ups?status=owned');
assert.equal(await page.getByRole('cell',{name:school.name,exact:true}).count(),0);
await page.screenshot({path:'output/evidence/R5-cancelled.png',fullPage:true});
await browser.close();
console.log('PASS R5/IQ5: saved Open Call; Not Interested cancels tasks, preserves task IDs and visits; absent from active list');
const manifest=JSON.parse(fs.readFileSync('output/evidence/manifest.json'));
for(const [file,caption] of [['R5-open.png','Open status offers Call and Meeting'],['R5-not-interested.png','Not Interested hides Next Action'],['R5-cancelled.png','Saved Not Interested removes follow-ups from active list; records retained']])manifest.push({item:'R5 / IQ5',caption,file});
fs.writeFileSync('output/evidence/manifest.json',JSON.stringify(manifest,null,2));
