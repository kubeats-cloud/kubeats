import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {chromium}=createRequire('D:/devcache/npm/_npx/e41f203b7505f1fb/node_modules/playwright/package.json')('playwright');
const browser=await chromium.launch();
const context=await browser.newContext({storageState:'output/evidence/Audit-Admin-session.json',viewport:{width:1600,height:1100}});
const page=await context.newPage();
await page.goto('http://127.0.0.1:3000/?from=2026-10-20&to=2026-10-20');
const table=page.locator('table').last();
const headers=await table.locator('thead tr').first().locator('th').allTextContents();
assert.deepEqual(headers.map(t=>t.trim()),['Institute','Meetings','Sessions','Campus Visits','Olympiad Registrations','Applications','Admissions']);
const rows=await table.locator('tbody tr').evaluateAll(nodes=>nodes.map(n=>[...n.querySelectorAll('th,td')].map(e=>e.textContent.trim())));
fs.writeFileSync('output/evidence/A1-table.json',JSON.stringify(rows));
const downloadPromise=page.waitForEvent('download');
await page.getByRole('link',{name:'Download Excel',exact:true}).click();
const download=await downloadPromise;
await download.saveAs('output/evidence/A1-filtered.xlsx');
await page.getByRole('link',{name:'Download Excel',exact:true}).scrollIntoViewIfNeeded();
await page.screenshot({path:'output/evidence/A1-exact-labels.png',fullPage:false});
await browser.close();
console.log('PASS A1 exact six names; downloaded filtered workbook');
