await page.waitForURL(`**/team/report?start=${f.today}&end=${f.today}`);
const link=page.getByRole('link',{name:'Download Field Visit Report',exact:true});
await link.waitFor();
await page.screenshot({path:'output/evidence/IQ4-date-range.png',fullPage:false});
const promise=page.waitForEvent('download');await link.click();
const download=await promise;assert.match(download.suggestedFilename(),/^field-visits-/);
await download.saveAs('output/evidence/IQ4-field-visits.xlsx');
