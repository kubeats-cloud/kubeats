import fs from 'node:fs';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {createClient} from '@supabase/supabase-js';
process.loadEnvFile('.env.local');
assert.equal(new URL(process.env.NEXT_PUBLIC_SUPABASE_URL).hostname,'127.0.0.1');
const db=createClient(process.env.NEXT_PUBLIC_SUPABASE_URL,process.env.SUPABASE_SERVICE_ROLE_KEY);
const ck=({data,error})=>{if(error)throw Error(error.message);return data;};
const f=JSON.parse(fs.readFileSync('output/evidence/fixtures.json'));
const a=JSON.parse(fs.readFileSync('output/evidence/accounts.json'))['Audit Alice'];
const school=f.institutes[3];
ck(await db.from('institutes').update({status:'First meeting done'}).eq('id',school.id));
const purpose=f.purposes.find(p=>p.label==='Follow-up');
const baseline=ck(await db.from('daily_plans').select('id')).map(x=>x.id);
const plan=ck(await db.from('daily_plans').insert({member:a.id,date:f.future,institute_id:school.id,purpose:purpose.label,purpose_id:purpose.id,checkout_missing:false}).select('id').single());
const todayPlan=ck(await db.from('daily_plans').insert({member:a.id,date:f.today,institute_id:school.id,purpose:purpose.label,purpose_id:purpose.id,checkout_missing:false}).select('id').single());
ck(await db.from('institutes').update({status:'Not Interested'}).eq('id',school.id));
const after=ck(await db.from('daily_plans').select('id,cancelled_at'));
assert(baseline.every(id=>after.some(p=>p.id===id)));
assert(after.find(p=>p.id===plan.id)?.cancelled_at);
const {error}=await db.from('daily_plans').update({checkin_at:new Date().toISOString(),checkin_lat:23.03,checkin_lng:72.58}).eq('id',todayPlan.id);
assert.equal(error?.code,'23514');
// Test DOWN inside a transaction and roll it back; no existing data is altered.
const down=fs.readFileSync('supabase/rollbacks/0047_preserve_cancelled_plans_down.sql','utf8').replace(/^begin;$/m,'').replace(/^commit;$/m,'');
const test=`begin; ${down}\ndo $$ begin if exists(select 1 from pg_trigger where tgname='daily_plans_guard_cancelled') then raise exception 'DOWN failed'; end if; if not exists(select 1 from public.daily_plans where id='${plan.id}' and cancelled_at is not null) then raise exception 'DOWN lost history'; end if; end $$; rollback;`;
const result=spawnSync('docker',['exec','-i','supabase_db_free_lance','psql','-U','postgres','-d','postgres','-v','ON_ERROR_STOP=1'],{input:test,encoding:'utf8'});
assert.equal(result.status,0,result.stderr);
console.log('PASS 0047: every existing plan retained, cancelled plan cannot check in, DOWN executes and retains cancellation history; rolled back to UP');
const {chromium}=createRequire('D:/devcache/npm/_npx/e41f203b7505f1fb/node_modules/playwright/package.json')('playwright');
const browser=await chromium.launch();
const page=await browser.newPage({storageState:'output/evidence/Audit-Alice-session.json',viewport:{width:1280,height:1000}});
await page.goto('http://127.0.0.1:3000/pending/follow-ups?status=owned');
assert.equal(await page.getByRole('cell',{name:school.name,exact:true}).count(),0);
await page.screenshot({path:'output/evidence/R5-preserved-plans.png',fullPage:true});
await browser.close();
const m=JSON.parse(fs.readFileSync('output/evidence/manifest.json'));
m.push({item:'R5 / IQ5',caption:'Cancelled follow-ups leave active lists; future plan retained in database',file:'R5-preserved-plans.png'});
fs.writeFileSync('output/evidence/manifest.json',JSON.stringify(m,null,2));
